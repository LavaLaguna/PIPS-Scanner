# Generate oui.h from Wireshark epan/manuf-data.c (MA-L /24, MA-M /28, MA-S /36 tables)
import re, sys, zlib
src, dst = sys.argv[1], sys.argv[2]
SUF = r'(,|\.|\s)+(co|corp|corporation|inc|incorporated|ltd|limited|llc|l\.l\.c|gmbh|ag|sa|s\.a|srl|s\.r\.l|bv|b\.v|oy|ab|as|a/s|kg|plc|pte|pty|spa|s\.p\.a|sas|nv|kk|k\.k|company|co\.,ltd|co ltd|technologies|technology|tech|electronics|electronic|international|holdings|group|systems?)\.?$'
CITY = r'^(hangzhou|zhejiang|shenzhen|guangzhou|guangdong|beijing|shanghai|tianjin|jiangsu|suzhou|xiamen|fujian|chengdu|wuhan|nanjing|dongguan|ningbo|qingdao|huizhou|zhuhai|sichuan|shandong|hefei|chongqing)\s+'
def clean(n):
    n = re.sub(r'\s+', ' ', n.encode('ascii', 'ignore').decode()).strip()
    for _ in range(5):
        m = re.sub(SUF, '', n, flags=re.I).strip(' ,.')
        if m == n or not m: break
        n = m
    m = re.sub(CITY, '', n, flags=re.I)
    return (m or n)[:30].strip(' ,.')
txt = open(src, encoding='utf-8', errors='replace').read()
tabs = {}
for name, nb in (('oui24', 3), ('oui28', 4), ('oui36', 5)):
    body = txt[txt.index('global_manuf_%s_table[]' % name):]
    body = body[:body.index('};')]
    d = {}
    for m in re.finditer(r'\{\s*\{\s*(0x[^}]*)\},\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\s*\}', body):
        b = [int(x, 16) for x in m.group(1).split(',')]
        long = m.group(3).encode().decode('unicode_escape', 'ignore') or m.group(2)
        d[bytes(b)] = clean(long)
    tabs[name] = d
names = sorted({v for d in tabs.values() for v in d.values()})
idx = {n: i for i, n in enumerate(names)}
def varint(n):
    o = bytearray()
    while n >= 128: o.append(n & 127 | 128); n >>= 7
    o.append(n); return o
raw = bytearray(varint(len(names)))
for n in names: raw += n.encode() + b'\0'
for name in ('oui24', 'oui28', 'oui36'):
    d = tabs[name]; prev = 0
    raw += varint(len(d))
    for k in sorted(d):
        v = int.from_bytes(k, 'big'); raw += varint(v - prev) + varint(idx[d[k]]); prev = v
c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
z = c.compress(bytes(raw)) + c.flush()
with open(dst, 'w') as o:
    o.write('/* generated by genoui.py from Wireshark epan/manuf-data.c - raw deflate */\n')
    o.write('#define OUI_RAW %d\nstatic const unsigned char OUI_Z[%d] = {\n' % (len(raw), len(z)))
    for i in range(0, len(z), 40): o.write(','.join(map(str, z[i:i+40])) + ',\n')
    o.write('};\n')

print({k: len(v) for k, v in tabs.items()}, 'names', len(names), 'raw', len(raw), 'deflate', len(z))
